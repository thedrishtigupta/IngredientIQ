"""Robustness checks for the research paper (ablation, per-category, sensitivity).

Needs data/research/cv_folds.csv from `python scripts/run_research.py`: the
ablation reuses its Model A / B fold scores (same seed, same splits).

Writes data/research/robustness_*.csv and docs/RESEARCH_ROBUSTNESS.md.

Run:  python scripts/run_robustness.py                (~30 min)
      python scripts/run_robustness.py --report-only  (rebuild the report from saved CSVs)
"""

import argparse
from datetime import date
from pathlib import Path
import sys
import time
import warnings

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from research import robustness  # noqa: E402
from research.combos import add_combo_features, mine_combinations  # noqa: E402
from research.dataset import TARGETS, build_study_data, load_sources  # noqa: E402
from research.report import METRIC_LABELS, _p, _table, _verdict  # noqa: E402

OUT = ROOT / "data" / "research"
REPORT = ROOT / "docs" / "RESEARCH_ROBUSTNESS.md"

VARIANT_LABELS = {
    "B": "B: + all ingredient features",
    "A+ingredients": "A + individual ingredients",
    "A+functional": "A + functional-group shares",
    "A+combinations": "A + combinations",
    "ingredients_only": "ingredients only (no metadata)",
}


def _comparison_table(comp, extra=()):
    comp = comp.copy()
    comp["metric"] = comp.primary_metric.map(lambda m: METRIC_LABELS[m][0])
    comp["A"] = [getattr(r, f"A_{r.primary_metric}") for r in comp.itertuples()]
    comp["variant score"] = [getattr(r, f"B_{r.primary_metric}") for r in comp.itertuples()]
    # verdict on the FDR-corrected q, not the nominal p (see robustness.with_fdr)
    comp["verdict"] = [("—" if pd.isna(q) else _verdict(g, q).replace("B better", "variant better"))
                       for g, q in zip(comp.gain, comp.q_corrected)]
    comp["target"] = comp.target.map(lambda t: TARGETS[t][1])
    comp["variant"] = comp.variant.map(lambda v: VARIANT_LABELS.get(v, v))
    cols = [*extra, "scope", "target", "variant", "metric", "A", "variant score", "gain", "p_corrected",
            "q_corrected", "verdict"]
    return _table(comp, cols, [*extra, "scope", "target", "variant", "metric", "A", "variant score", "gain",
                               "p (corr.)", "q (FDR)", "verdict"],
                  fmt={"p_corrected": _p, "q_corrected": _p, "gain": lambda v: f"{v:+.3f}"})


def compute():
    main_folds = pd.read_csv(OUT / "cv_folds.csv")
    sources = load_sources(ROOT / "data")
    study = build_study_data(sources)
    combos = mine_combinations(study.frame, study.ingredient_cols)
    study.frame, study.combo_cols = add_combo_features(study.frame, combos)

    t = time.time()
    print("== Ablation", flush=True)
    robustness.ablation(study, main_folds).to_csv(OUT / "robustness_ablation.csv", index=False)
    print(f"({time.time() - t:.0f}s)\n== Per-category models", flush=True)
    robustness.per_category(study).to_csv(OUT / "robustness_categories.csv", index=False)
    print(f"({time.time() - t:.0f}s)\n== Sensitivity", flush=True)
    sens_tests, sens_models = robustness.sensitivity(sources)
    sens_tests.to_csv(OUT / "robustness_sensitivity_tests.csv", index=False)
    sens_models.to_csv(OUT / "robustness_sensitivity_models.csv", index=False)
    print(f"({time.time() - t:.0f}s)")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--report-only", action="store_true",
                        help="rebuild the report from the saved robustness_*.csv (re-applies the FDR correction)")
    args = parser.parse_args()
    warnings.filterwarnings("ignore", category=UserWarning)
    warnings.filterwarnings("ignore", category=FutureWarning)
    if not args.report_only:
        compute()

    abl = robustness.with_fdr(pd.read_csv(OUT / "robustness_ablation.csv"), exclude=robustness.NOT_TESTED)
    cat = robustness.with_fdr(pd.read_csv(OUT / "robustness_categories.csv"))
    sens_tests = pd.read_csv(OUT / "robustness_sensitivity_tests.csv")
    sens_models = robustness.with_fdr(pd.read_csv(OUT / "robustness_sensitivity_models.csv"), "setting")
    for df, name in [(abl, "ablation"), (cat, "categories"), (sens_models, "sensitivity_models")]:
        df.to_csv(OUT / f"robustness_{name}.csv", index=False)

    tests = sens_tests[sens_tests.scope != "prespecified"].copy()
    tests["target"] = tests.target.map(lambda x: TARGETS[x][1])
    pre = sens_tests[sens_tests.scope == "prespecified"]
    out = [
        "# Research robustness checks",
        "",
        f"*Generated by `scripts/run_robustness.py` on {date.today().isoformat()}. Do not edit by hand."
        " Method: [RESEARCH.md](RESEARCH.md); main results: [RESEARCH_RESULTS.md](RESEARCH_RESULTS.md).*",
        "",
        "All comparisons use LightGBM. `gain` = variant − Model A on the primary metric (R² or ROC-AUC);"
        " `p (corr.)` = Nadeau–Bengio corrected t-test; `q (FDR)` = Benjamini–Hochberg over that table"
        " (per setting for sensitivity). The verdict uses q: with dozens of comparisons, a few nominal"
        " p < 0.05 are expected by chance.",
        "",
        "## 1. Ablation: which ingredient features matter? (random 5-fold ×3)",
        "",
        "`ingredients only` uses no metadata at all, so its gain is measured against Model A as a"
        " reference point, not as an improvement.",
        "",
        _comparison_table(abl),
        "",
        "## 2. Per-category models (Model A vs Model B)",
        "",
        _comparison_table(cat, extra=("cv",)),
        "",
        "## 3. Sensitivity of the main conclusions",
        "",
        "### Model A vs Model B (5-fold, 1 repeat)",
        "",
        _comparison_table(sens_models, extra=("setting", "products")),
        "",
        "### Association tests",
        "",
        _table(tests, ["setting", "products", "scope", "target", "tests", "significant_raw",
                       "significant_adjusted", "robust"],
               ["setting", "products", "scope", "target", "tests", "q<0.05 raw", "q<0.05 adjusted", "robust"]),
        "",
        "### Pre-specified hypotheses (scope All)",
        "",
        _table(pre, ["setting", "target", "significant_raw", "significant_adjusted", "robust"],
               ["setting", "outcome: combination", "raw q<0.05", "adjusted q<0.05", "robust"]),
        "",
    ]
    REPORT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {REPORT.relative_to(ROOT)} and data/research/robustness_*.csv")


if __name__ == "__main__":
    main()
